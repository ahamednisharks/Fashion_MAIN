const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = resolve(root, 'node_modules/bootstrap-icons/icons');
const outFile = resolve(root, 'src/app/shared/components/icon/icon-registry.ts');

const entries = [...new Set(ICON_NAMES)].sort().map((name) => {
  const svg = readFileSync(resolve(iconsDir, `${name}.svg`), 'utf8');
  const body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .trim();
  return `  '${name}': '${body.replace(/'/g, "\\'")}',`;
});

const output = `// AUTO-GENERATED by scripts/generate-icons.mjs from bootstrap-icons. Do not edit by hand.
// Run \`npm run icons\` after changing the icon list in that script.

export const ICON_REGISTRY = {
${entries.join('\n')}
} as const;

export type IconName = keyof typeof ICON_REGISTRY;
`;

writeFileSync(outFile, output);
console.log(`Generated ${entries.length} icons -> ${outFile}`);
